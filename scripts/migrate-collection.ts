// One-time migration from the schemaVersion 1 documents to the content tree.
// Kept for provenance. It refuses to overwrite an existing content tree.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { stringify } from 'yaml';
import type { Collection, GitHubData } from '../src/data/schema';
import type { GitHubObservation, HistoryEvent, Thing, ThingSource, Topic } from '../collection/schema';
import { saveObservation } from '../collection/observations';

const yaml = (value: unknown) => stringify(value, { lineWidth: 0 });
const legacy = JSON.parse(await readFile('src/data/collection.json', 'utf8')) as Collection;
const github = JSON.parse(await readFile('src/data/github.json', 'utf8')) as GitHubData;
if ((await readdir('content/things').catch(() => [])).length) throw new Error('content/things already has files.');
await mkdir('content/things', { recursive: true });
await mkdir('content/history', { recursive: true });

const sourceById = new Map(legacy.sources.map((s) => [s.id, s]));
for (const thing of legacy.things) {
  const sources: ThingSource[] = thing.sources.map((attachment) => {
    const source = sourceById.get(attachment.sourceId);
    if (!source) throw new Error(`Unknown source ${attachment.sourceId}`);
    if (source.kind === 'github')
      return {
        kind: 'github',
        repository: source.repository,
        role: attachment.role,
        ...(attachment.path ? { path: attachment.path } : {})
      };
    return {
      kind: 'website',
      url: source.url,
      role: attachment.role,
      ...(source.kind === 'website' && source.sitemap ? { sitemap: source.sitemap } : {})
    };
  });
  const { idea, ...story } = thing.story ?? { idea: '' };
  const frontmatter: Omit<Thing, 'id' | 'body'> = {
    title: thing.title,
    summary: thing.summary,
    collection: thing.collection,
    // Historical becomes retired. Refine to dormant or archived by hand where that is the better word.
    status: thing.historical ? 'retired' : 'active',
    url: thing.url,
    topics: legacy.topics.filter((t) => t.projectIds.includes(thing.id)).map((t) => t.id),
    sources,
    connections: legacy.connections.filter((edge) => edge.from === thing.id).map(({ from: _from, ...edge }) => edge),
    ...(thing.story ? { story: story as Thing['story'] } : {})
  };
  await writeFile(
    join('content/things', `${thing.id}.md`),
    `---\n${yaml(frontmatter)}---\n${idea ? `\n${idea}\n` : ''}`
  );
}
const topics: Topic[] = legacy.topics.map(({ id, title, description }) => ({ id, title, description }));
await writeFile('content/topics.yaml', yaml(topics));
const byYear = new Map<string, HistoryEvent[]>();
for (const event of legacy.history) {
  const year = event.date.slice(0, 4);
  byYear.set(year, [
    ...(byYear.get(year) ?? []),
    {
      id: event.id,
      date: event.date,
      kind: event.kind,
      title: event.title,
      summary: event.summary,
      source: event.source,
      things: event.projectIds
    }
  ]);
}
for (const [year, events] of byYear)
  await writeFile(
    join('content/history', `${year}.yaml`),
    yaml(events.toSorted((a, b) => b.date.localeCompare(a.date) || a.id.localeCompare(b.id)))
  );
for (const snapshot of github.repositories) {
  const { sourceId: _sourceId, fetchedAt, ...rest } = snapshot;
  const observation: GitHubObservation = { kind: 'github', ...rest, observedAt: fetchedAt };
  await saveObservation(observation);
}
await writeFile(
  'data/observations/README.md',
  `# Observations\n\nGenerated by \`npm run collect\`. Do not edit by hand.\n`
);

console.log(
  `Migrated ${legacy.things.length} things, ${topics.length} topics, ${legacy.history.length} events, ${github.repositories.length} observations.`
);
