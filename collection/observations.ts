import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { format } from 'prettier';
import {
  githubKey,
  websiteKey,
  type GitHubObservation,
  type Observation,
  type ScreenshotObservation,
  type TinylyticsObservation,
  type WaybackObservation,
  type WebObservation
} from './schema';

const observationsRoot = 'data/observations';

export function observationPath(observation: Observation, root = observationsRoot) {
  if (observation.kind === 'github') return join(root, 'github', `${githubKey(observation.repository)}.json`);
  return join(root, observation.kind, `${websiteKey(observation.url)}.json`);
}
async function readDirectory(directory: string): Promise<unknown[]> {
  const names = (await readdir(directory).catch(() => [] as string[])).filter((n) => n.endsWith('.json')).sort();
  return Promise.all(names.map(async (name) => JSON.parse(await readFile(join(directory, name), 'utf8'))));
}
function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === 'object' && !Array.isArray(value);
}
// Observations are generated by this repository's own collector, so the check is a shape check,
// enough to catch a hand edit or a truncated file rather than a full schema validation.
function github(value: unknown): GitHubObservation {
  if (
    !isRecord(value) ||
    value.kind !== 'github' ||
    typeof value.repository !== 'string' ||
    typeof value.observedAt !== 'string' ||
    !Array.isArray(value.activity)
  )
    throw new Error('Invalid GitHub observation.');
  return value as unknown as GitHubObservation;
}
function web(value: unknown): WebObservation {
  if (!isRecord(value) || value.kind !== 'web' || typeof value.url !== 'string' || typeof value.observedAt !== 'string')
    throw new Error('Invalid web observation.');
  return value as unknown as WebObservation;
}
function tinylytics(value: unknown): TinylyticsObservation {
  if (
    !isRecord(value) ||
    value.kind !== 'tinylytics' ||
    typeof value.url !== 'string' ||
    typeof value.observedAt !== 'string' ||
    !Array.isArray(value.months)
  )
    throw new Error('Invalid Tinylytics observation.');
  return value as unknown as TinylyticsObservation;
}
function wayback(value: unknown): WaybackObservation {
  if (
    !isRecord(value) ||
    value.kind !== 'wayback' ||
    typeof value.url !== 'string' ||
    typeof value.observedAt !== 'string' ||
    !Array.isArray(value.years)
  )
    throw new Error('Invalid Wayback observation.');
  return value as unknown as WaybackObservation;
}
function screenshot(value: unknown): ScreenshotObservation {
  if (
    !isRecord(value) ||
    value.kind !== 'screenshot' ||
    typeof value.url !== 'string' ||
    typeof value.observedAt !== 'string' ||
    typeof value.image !== 'string' ||
    !/^[a-z0-9-]+\.jpg$/.test(value.image) ||
    typeof value.sha256 !== 'string' ||
    !/^[a-f0-9]{64}$/.test(value.sha256)
  )
    throw new Error('Invalid screenshot observation.');
  return value as unknown as ScreenshotObservation;
}
export async function loadObservations(root = observationsRoot): Promise<Observation[]> {
  const [githubFiles, webFiles, tinylyticsFiles, waybackFiles, screenshotFiles] = await Promise.all([
    readDirectory(join(root, 'github')),
    readDirectory(join(root, 'web')),
    readDirectory(join(root, 'tinylytics')),
    readDirectory(join(root, 'wayback')),
    readDirectory(join(root, 'screenshot'))
  ]);
  return [
    ...githubFiles.map(github),
    ...webFiles.map(web),
    ...tinylyticsFiles.map(tinylytics),
    ...waybackFiles.map(wayback),
    ...screenshotFiles.map(screenshot)
  ];
}
// A screenshot's JPEG sits beside its observation, under the same key.
const screenshotImagePath = (observation: ScreenshotObservation, root = observationsRoot) =>
  join(root, 'screenshot', observation.image);
async function formatJson(value: unknown) {
  return format(JSON.stringify(value), { parser: 'json', printWidth: 120, tabWidth: 2 });
}
export async function saveObservation(observation: Observation, root = observationsRoot) {
  const path = observationPath(observation, root);
  await mkdir(join(path, '..'), { recursive: true });
  await writeFile(path, await formatJson(observation));
  return path;
}
// The image first, so an observation never names a JPEG that is not there.
export async function saveScreenshot(observation: ScreenshotObservation, image: Uint8Array, root = observationsRoot) {
  const path = screenshotImagePath(observation, root);
  await mkdir(join(path, '..'), { recursive: true });
  await writeFile(path, image);
  return saveObservation(observation, root);
}
